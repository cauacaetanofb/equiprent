CREATE TABLE chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id bigint NOT NULL REFERENCES reservation(id) ON DELETE RESTRICT,
    author_id bigint NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    author_role varchar(10) NOT NULL CHECK (author_role IN ('ADMIN','CLIENTE')),
    submission_token uuid NOT NULL,
    body varchar(2000) NOT NULL CHECK (body ~ '[^[:space:]]'),
    sent_at timestamptz NOT NULL,
    CONSTRAINT uk_chat_submission UNIQUE(reservation_id,author_id,submission_token)
);
CREATE INDEX ix_chat_history ON chat_message(reservation_id,id);
CREATE INDEX ix_chat_rate ON chat_message(reservation_id,author_id,sent_at);

