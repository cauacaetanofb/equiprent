CREATE TABLE reservation_offer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id bigint NOT NULL REFERENCES reservation(id) ON DELETE RESTRICT,
    version integer NOT NULL CHECK (version > 0),
    author_id bigint NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    daily_rate numeric(12,2) NOT NULL CHECK (daily_rate > 0 AND daily_rate <> 'NaN'::numeric),
    amount numeric(14,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    terms varchar(2000) NOT NULL,
    created_at timestamptz NOT NULL,
    accepted_by_id bigint REFERENCES app_user(id) ON DELETE RESTRICT,
    accepted_at timestamptz,
    CONSTRAINT uk_offer_version UNIQUE(reservation_id,version),
    CONSTRAINT ck_offer_acceptance CHECK (
        (accepted_by_id IS NULL AND accepted_at IS NULL) OR
        (accepted_by_id IS NOT NULL AND accepted_at IS NOT NULL AND accepted_at >= created_at)
    )
);
ALTER TABLE reservation
    ADD CONSTRAINT fk_reservation_current_offer FOREIGN KEY(id,current_offer_version)
        REFERENCES reservation_offer(reservation_id,version) DEFERRABLE INITIALLY DEFERRED,
    ADD CONSTRAINT fk_reservation_contract_offer FOREIGN KEY(id,contract_offer_version)
        REFERENCES reservation_offer(reservation_id,version) DEFERRABLE INITIALLY DEFERRED,
    ADD CONSTRAINT ck_reservation_contract CHECK (
        (contract_daily_rate IS NULL AND contract_amount IS NULL AND contract_terms IS NULL AND contract_offer_version IS NULL AND approved_at IS NULL) OR
        (contract_daily_rate IS NOT NULL AND contract_amount IS NOT NULL AND
         contract_daily_rate > 0 AND contract_daily_rate <> 'NaN'::numeric AND contract_amount > 0 AND contract_amount <> 'NaN'::numeric)
    ),
    ADD CONSTRAINT ck_reservation_approval CHECK (
        (contract_offer_version IS NULL AND approved_at IS NULL) OR
        (contract_offer_version IS NOT NULL AND approved_at IS NOT NULL AND contract_offer_version = current_offer_version AND contract_terms IS NOT NULL)
    );
