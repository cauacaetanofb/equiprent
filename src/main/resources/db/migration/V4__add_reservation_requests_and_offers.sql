    (status='REQUESTED' AND request_token IS NOT NULL AND current_offer_version IS NOT NULL AND contract_daily_rate IS NULL AND picked_up_at IS NULL AND returned_at IS NULL AND cancelled_at IS NULL AND rejected_at IS NULL)
    OR (status='REJECTED' AND request_token IS NOT NULL AND current_offer_version IS NOT NULL AND contract_daily_rate IS NULL AND rejected_at IS NOT NULL AND picked_up_at IS NULL AND returned_at IS NULL AND cancelled_at IS NULL)
    OR (status='RESERVED' AND contract_daily_rate IS NOT NULL AND picked_up_at IS NULL AND returned_at IS NULL AND cancelled_at IS NULL AND rejected_at IS NULL)
    OR (status='IN_USE' AND contract_daily_rate IS NOT NULL AND picked_up_at IS NOT NULL AND returned_at IS NULL AND cancelled_at IS NULL AND rejected_at IS NULL)
    OR (status='RETURNED' AND contract_daily_rate IS NOT NULL AND picked_up_at IS NOT NULL AND returned_at IS NOT NULL AND cancelled_at IS NULL AND rejected_at IS NULL)
