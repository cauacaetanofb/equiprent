CREATE TABLE app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    email varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL,
    active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_app_user_email_normalized CHECK (email = lower(btrim(email)) AND length(email) > 0),
    CONSTRAINT ck_app_user_password_hash CHECK (length(btrim(password_hash)) > 0),
    CONSTRAINT ck_app_user_role CHECK (role IN ('ADMIN', 'CLIENTE'))
);

CREATE TABLE equipment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code varchar(50) NOT NULL,
    name varchar(120) NOT NULL,
    description varchar(2000) NOT NULL,
    category varchar(20) NOT NULL,
    daily_rate numeric(12,2) NOT NULL,
    condition varchar(20) NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uk_equipment_asset_code UNIQUE (asset_code),
    CONSTRAINT ck_equipment_asset_code CHECK (asset_code = btrim(asset_code) AND length(asset_code) > 0),
    CONSTRAINT ck_equipment_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_equipment_description CHECK (length(btrim(description)) > 0),
    CONSTRAINT ck_equipment_category CHECK (category IN ('NOTEBOOK', 'CAMERA', 'TOOL', 'OTHER')),
    CONSTRAINT ck_equipment_daily_rate CHECK (daily_rate > 0 AND daily_rate <> 'NaN'::numeric),
    CONSTRAINT ck_equipment_condition CHECK (condition IN ('OPERATIONAL', 'MAINTENANCE', 'RETIRED')),
    CONSTRAINT ck_equipment_timestamps CHECK (updated_at >= created_at)
);

CREATE TABLE reservation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL,
    equipment_id bigint NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    status varchar(20) NOT NULL,
    daily_rate_snapshot numeric(12,2) NOT NULL,
    estimated_amount numeric(14,2) NOT NULL,
    created_at timestamptz NOT NULL,
    picked_up_at timestamptz,
    returned_at timestamptz,
    cancelled_at timestamptz,
    CONSTRAINT fk_reservation_customer FOREIGN KEY (customer_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservation_period CHECK (end_date >= start_date),
    CONSTRAINT ck_reservation_status CHECK (status IN ('RESERVED', 'IN_USE', 'RETURNED', 'CANCELLED')),
    CONSTRAINT ck_reservation_daily_rate CHECK (daily_rate_snapshot > 0 AND daily_rate_snapshot <> 'NaN'::numeric),
    CONSTRAINT ck_reservation_amount CHECK (estimated_amount > 0 AND estimated_amount <> 'NaN'::numeric),
    CONSTRAINT ck_reservation_state_timestamps CHECK (
        (status = 'RESERVED' AND picked_up_at IS NULL AND returned_at IS NULL AND cancelled_at IS NULL)
        OR (status = 'IN_USE' AND picked_up_at IS NOT NULL AND returned_at IS NULL AND cancelled_at IS NULL)
        OR (status = 'RETURNED' AND picked_up_at IS NOT NULL AND returned_at IS NOT NULL AND cancelled_at IS NULL)
        OR (status = 'CANCELLED' AND picked_up_at IS NULL AND returned_at IS NULL AND cancelled_at IS NOT NULL)
    ),
    CONSTRAINT ck_reservation_timestamp_order CHECK (
        (picked_up_at IS NULL OR picked_up_at >= created_at)
        AND (returned_at IS NULL OR returned_at >= picked_up_at)
        AND (cancelled_at IS NULL OR cancelled_at >= created_at)
    )
);

CREATE TABLE reservation_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id bigint NOT NULL,
    actor_id bigint NOT NULL,
    previous_status varchar(20),
    new_status varchar(20) NOT NULL,
    occurred_at timestamptz NOT NULL,
    note varchar(1000),
    CONSTRAINT fk_reservation_event_reservation FOREIGN KEY (reservation_id) REFERENCES reservation (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_event_actor FOREIGN KEY (actor_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservation_event_previous_status CHECK (previous_status IN ('RESERVED', 'IN_USE', 'RETURNED', 'CANCELLED')),
    CONSTRAINT ck_reservation_event_new_status CHECK (new_status IN ('RESERVED', 'IN_USE', 'RETURNED', 'CANCELLED')),
    CONSTRAINT ck_reservation_event_transition CHECK (
        (previous_status IS NULL AND new_status = 'RESERVED')
        OR (previous_status IS NOT NULL AND (
            (previous_status = 'RESERVED' AND new_status IN ('IN_USE', 'CANCELLED'))
            OR (previous_status = 'IN_USE' AND new_status = 'RETURNED')
        ))
    )
);

CREATE INDEX idx_reservation_equipment_period ON reservation (equipment_id, status, start_date, end_date);
CREATE INDEX idx_reservation_customer_created ON reservation (customer_id, created_at DESC, id DESC);
CREATE INDEX idx_reservation_event_timeline ON reservation_event (reservation_id, occurred_at, id);
CREATE INDEX idx_reservation_event_actor ON reservation_event (actor_id);
