CREATE TABLE company (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(120) NOT NULL CHECK (length(btrim(name)) > 0),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_company_code CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,49}$')
);

INSERT INTO company (code, name) VALUES ('INITIAL', 'Empresa inicial');

-- M1: uma empresa administrativa por conta; vários administradores por empresa.
CREATE TABLE company_membership (
    user_id bigint PRIMARY KEY REFERENCES app_user(id) ON DELETE RESTRICT,
    company_id bigint NOT NULL REFERENCES company(id) ON DELETE RESTRICT,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_membership_company ON company_membership(company_id);
INSERT INTO company_membership (user_id, company_id)
SELECT u.id, c.id FROM app_user u CROSS JOIN company c WHERE u.role = 'ADMIN' AND c.code = 'INITIAL';

-- Bloqueio comercial local, sem desativar a conta pessoal em outras empresas.
CREATE TABLE company_customer (
    company_id bigint NOT NULL REFERENCES company(id) ON DELETE RESTRICT,
    user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (company_id, user_id)
);
INSERT INTO company_customer (company_id, user_id)
SELECT c.id, u.id FROM app_user u CROSS JOIN company c WHERE u.role = 'CLIENTE' AND c.code = 'INITIAL';

